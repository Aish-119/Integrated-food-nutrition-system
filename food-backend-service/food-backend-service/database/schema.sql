
-- 1. Food items
CREATE TABLE IF NOT EXISTS public.food_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(255),
    quantity NUMERIC NOT NULL,
    unit VARCHAR(255) NOT NULL,
    expiry_date DATE
);

-- 2. Beneficiaries
CREATE TABLE IF NOT EXISTS public.beneficiaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    age INTEGER,
    household_size INTEGER NOT NULL,
    nutrition_needs VARCHAR(255),
    address VARCHAR(255)
);

-- 3. Suppliers
CREATE TABLE IF NOT EXISTS public.suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    contact_person VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    address TEXT
);

-- 4. Nutrition values
CREATE TABLE IF NOT EXISTS public.nutrition_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    calories NUMERIC(10,2),
    protein NUMERIC(10,2),
    carbohydrates NUMERIC(10,2),
    fat NUMERIC(10,2),
    vitamins TEXT,
    minerals TEXT
);

-- 5. Nutrition programmes
CREATE TABLE IF NOT EXISTS public.nutrition_programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    start_date DATE,
    end_date DATE,
    status VARCHAR(255)
);

-- 6. Inventory batches
CREATE TABLE IF NOT EXISTS public.inventory_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    batch_number VARCHAR(255),
    quantity NUMERIC NOT NULL,
    unit VARCHAR(255) NOT NULL,
    received_date DATE,
    expiry_date DATE
);

-- 7. Procurements
CREATE TABLE IF NOT EXISTS public.procurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    quantity NUMERIC NOT NULL,
    procurement_date DATE NOT NULL,
    supplier VARCHAR(255)
);

-- 8. Distributions
CREATE TABLE IF NOT EXISTS public.distributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beneficiary_id BIGINT NOT NULL REFERENCES public.beneficiaries(id),
    distribution_date DATE NOT NULL,
    status VARCHAR(255) NOT NULL
);

-- 9. Meal plans
CREATE TABLE IF NOT EXISTS public.meal_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT REFERENCES public.nutrition_programmes(id),
    name VARCHAR(255) NOT NULL,
    meal_type VARCHAR(255),
    description TEXT,
    planned_date DATE,
    notes TEXT
);

-- 10. Programme participation
CREATE TABLE IF NOT EXISTS public.programme_participation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programme_id BIGINT NOT NULL REFERENCES public.nutrition_programmes(id),
    beneficiary_id BIGINT NOT NULL REFERENCES public.beneficiaries(id),
    enrollment_date DATE,
    status VARCHAR(255)
);

-- 11. Distribution items
CREATE TABLE IF NOT EXISTS public.distribution_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distribution_id BIGINT NOT NULL REFERENCES public.distributions(id),
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    quantity NUMERIC NOT NULL,
    unit VARCHAR(255) NOT NULL
);

-- 12. Stock movements
CREATE TABLE IF NOT EXISTS public.stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    batch_id BIGINT REFERENCES public.inventory_batches(id),
    movement_type VARCHAR(255) NOT NULL,
    quantity NUMERIC NOT NULL,
    movement_date DATE,
    remarks TEXT
);

-- 13. Quality inspections
CREATE TABLE IF NOT EXISTS public.quality_inspections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    batch_id BIGINT REFERENCES public.inventory_batches(id),
    inspection_date DATE,
    inspector_name VARCHAR(255),
    quality_status VARCHAR(255),
    remarks TEXT
);

-- 14. Wastage records
CREATE TABLE IF NOT EXISTS public.wastage_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    food_item_id BIGINT NOT NULL REFERENCES public.food_items(id),
    batch_id BIGINT REFERENCES public.inventory_batches(id),
    quantity NUMERIC NOT NULL,
    unit VARCHAR(255) NOT NULL,
    wastage_reason VARCHAR(255),
    wastage_date DATE,
    remarks TEXT
);